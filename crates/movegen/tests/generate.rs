//! Generation over the fixture corpus (docs/SPEC.md §T, §N, §C).
//!
//! The corpus bindings are committed in `crates/movegen-e2e/src/generated`, where they are
//! compiled (natively, under clippy, and for wasm) and exercised. This test fails when that tree
//! is stale; regenerate it with `MOVEGEN_BLESS=1 cargo test -p movegen --test generate`.

mod common;

use std::path::PathBuf;

use common::{Fixtures, miso_config};
use movegen::{Change, Config, generate, refresh};

fn e2e_config() -> Config {
    let mut config = miso_config();
    // Every Miso package, plus the framework as a stress test for the generator.
    let mut scope: Vec<String> = config.packages.keys().cloned().collect();
    scope.extend(["sui".to_owned(), "std".to_owned()]);
    config.generate.functions = Some(scope);
    config
}

fn e2e_out() -> PathBuf {
    PathBuf::from(env!("CARGO_MANIFEST_DIR")).join("../movegen-e2e/src/generated")
}

// spec: L-DET-1 (generation is a pure function of config + lock)
#[test]
fn e2e_bindings_are_up_to_date() {
    let config = e2e_config();
    let lock = refresh(&config, &Fixtures).unwrap();
    let generated = generate(&config, &lock).unwrap();
    assert_eq!(
        generated,
        generate(&config, &lock).unwrap(),
        "generation is deterministic"
    );
    let bless = std::env::var_os("MOVEGEN_BLESS").is_some();
    let changes = generated.sync(&e2e_out(), !bless).unwrap();
    // The deployments the e2e tests load (the ABIs are not needed there).
    let mut stale_deployments = Vec::new();
    for (rel, contents) in lock
        .files()
        .into_iter()
        .filter(|(p, _)| p.starts_with("deployments"))
    {
        let path = e2e_out().join("../..").join(&rel);
        if std::fs::read_to_string(&path).is_ok_and(|old| old == contents) {
            continue;
        }
        if bless {
            std::fs::create_dir_all(path.parent().unwrap()).unwrap();
            std::fs::write(&path, contents).unwrap();
        }
        stale_deployments.push(rel);
    }
    assert!(
        bless || stale_deployments.is_empty(),
        "stale e2e deployments: {stale_deployments:?}"
    );
    assert!(
        bless || changes.is_empty(),
        "crates/movegen-e2e/src/generated is stale ({} changes, first {:?}); rerun with MOVEGEN_BLESS=1",
        changes.len(),
        changes.first()
    );
}

// spec: C-CALL-1, C-CALL-2, N-MOD-1, N-FMT-1, T-DOC-1
#[test]
fn tree_shape() {
    let config = e2e_config();
    let lock = refresh(&config, &Fixtures).unwrap();
    let generated = generate(&config, &lock).unwrap();
    let file = |path: &str| {
        &generated
            .files
            .iter()
            .find(|(p, _)| p == &PathBuf::from(path))
            .unwrap_or_else(|| panic!("no {path}"))
            .1
    };
    // Every `mod` declaration is rustfmt-skipped; every file documents itself.
    for (path, contents) in &generated.files {
        assert!(
            contents.starts_with("// @generated by movegen"),
            "{}",
            path.display()
        );
        assert!(
            contents.contains("//!"),
            "{} has no module doc",
            path.display()
        );
        let lines: Vec<&str> = contents.lines().collect();
        for (i, line) in lines.iter().enumerate() {
            if line.starts_with("pub mod ") && line.ends_with(';') {
                assert_eq!(
                    lines[i - 1],
                    "#[rustfmt::skip]",
                    "{}: {line}",
                    path.display()
                );
            }
        }
    }
    assert!(file("mod.rs").contains("pub const PACKAGES: &[&str]"));
    // Every public/entry function of a selected module has a target; builders exist exactly
    // for the PTB-callable ones.
    let part = &lock.networks["mainnet"];
    let (mut builders, mut targets_only) = (0, 0);
    let scope = config.generate.functions.as_ref().unwrap();
    for (package, abi) in part.packages.iter().filter(|(p, _)| scope.contains(p)) {
        for module in &abi.modules {
            let path = format!("{package}/{}.rs", module.name);
            for f in module.functions.iter().filter(|f| {
                f.visibility == movegen_bytecode::abi::FunctionVisibility::Public || f.entry
            }) {
                let contents = file(&path);
                let meta = if module.datatypes.iter().any(|d| d.name == f.name) {
                    format!("{}_call", f.name)
                } else {
                    f.name.clone()
                };
                let meta = if is_keyword(&meta) {
                    format!("r#{meta}")
                } else {
                    meta
                };
                let name = if is_keyword(&f.name) {
                    format!("r#{}", f.name)
                } else {
                    f.name.clone()
                };
                assert!(
                    contents.contains(&format!("pub mod {meta} {{")),
                    "{path}: no target for {}",
                    f.name
                );
                let has_builder = contents.contains(&format!("pub fn {name}(\n"));
                let callable = !f.returns.iter().any(|t| {
                    matches!(t, movegen_bytecode::abi::Type::Reference(_) | movegen_bytecode::abi::Type::MutableReference(_))
                }) && !f.parameters.iter().any(|t| {
                    matches!(t, movegen_bytecode::abi::Type::Datatype(d) if d.module == "tx_context" && d.name == "TxContext")
                });
                assert_eq!(has_builder, callable, "{path}: {}", f.name);
                if callable {
                    builders += 1;
                } else {
                    targets_only += 1;
                }
            }
        }
    }
    assert!(
        builders > 1_000 && targets_only > 50,
        "{builders} builders, {targets_only} target-only"
    );
}

