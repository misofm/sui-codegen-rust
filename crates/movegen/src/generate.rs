//! Generation: the lock's reference-network ABIs → a Rust module tree (T, N, C rules).
//!
//! ```text
//! <output>/mod.rs                 `pub mod <package>;` + PACKAGES
//! <output>/<package>/mod.rs       `pub mod <module>;`
//! <output>/<package>/<module>.rs  types, and call builders for selected functions
//! ```
//!
//! Cross-module references are relative (`super::super::pkg::module::Type`), so the tree can be
//! mounted anywhere. Output is formatted with `prettyplease` and fully deterministic. Generated
//! `mod` declarations carry `#[rustfmt::skip]` (so `cargo fmt` never fights `generate --check`);
//! mount the root the same way: `#[rustfmt::skip] mod generated;`.

use std::collections::{BTreeMap, BTreeSet};
use std::path::{Path, PathBuf};

use movegen_bytecode::abi::{self, DatatypeKind, FunctionVisibility, Type};
use proc_macro2::{Ident, Span, TokenStream};
use quote::{format_ident, quote};

use crate::Error;
use crate::config::Config;
use crate::lock::{Lock, PackageAbi};

/// Generated files, relative to the output directory.
#[derive(Clone, Debug, PartialEq, Eq)]
pub struct Generated {
    /// `(relative path, contents)`, in path order.
    pub files: Vec<(PathBuf, String)>,
}

/// First line of every generated file; files carrying it are owned by `movegen`.
const MARKER: &str = "// @generated by movegen";

/// How a file under the output directory differs from the generated tree.
#[derive(Clone, Debug, PartialEq, Eq, PartialOrd, Ord)]
pub enum Change {
    /// Missing or different on disk.
    Write(PathBuf),
    /// A generated file that is no longer produced (a module or package went away).
    Remove(PathBuf),
}

impl Generated {
    /// Brings `out` in line with the generated tree: writes only changed files and removes
    /// generated files that are no longer produced (never files without the `@generated`
    /// marker). With `check`, touches nothing and only reports. Returns the changes, sorted.
    pub fn sync(&self, out: &Path, check: bool) -> Result<Vec<Change>, Error> {
        let mut changes = Vec::new();
        for (rel, contents) in &self.files {
            let path = out.join(rel);
            if std::fs::read_to_string(&path).is_ok_and(|old| old == *contents) {
                continue;
            }
            changes.push(Change::Write(rel.clone()));
            if !check {
                if let Some(parent) = path.parent() {
                    std::fs::create_dir_all(parent).map_err(|e| Error::io(parent, &e))?;
                }
                std::fs::write(&path, contents).map_err(|e| Error::io(&path, &e))?;
            }
        }
        let produced: BTreeSet<&Path> = self.files.iter().map(|(p, _)| p.as_path()).collect();
        let mut existing = Vec::new();
        generated_files(out, Path::new(""), &mut existing)?;
        for rel in existing
            .into_iter()
            .filter(|rel| !produced.contains(rel.as_path()))
        {
            if !check {
                let path = out.join(&rel);
                std::fs::remove_file(&path).map_err(|e| Error::io(&path, &e))?;
                // Drop the directory if that emptied it (a removed package).
                if let Some(parent) = path.parent().filter(|p| *p != out) {
                    let _ = std::fs::remove_dir(parent);
                }
            }
            changes.push(Change::Remove(rel));
        }
        changes.sort();
        Ok(changes)
    }
}

/// Collects `.rs` files under `dir` that start with [`MARKER`], relative to the output root.
fn generated_files(root: &Path, rel: &Path, out: &mut Vec<PathBuf>) -> Result<(), Error> {
    let dir = root.join(rel);
    let entries = match std::fs::read_dir(&dir) {
        Ok(entries) => entries,
        Err(e) if e.kind() == std::io::ErrorKind::NotFound => return Ok(()),
        Err(e) => return Err(Error::io(&dir, &e)),
    };
    for entry in entries {
        let entry = entry.map_err(|e| Error::io(&dir, &e))?;
        let child = rel.join(entry.file_name());
        let kind = entry
            .file_type()
            .map_err(|e| Error::io(&entry.path(), &e))?;
        if kind.is_dir() {
            generated_files(root, &child, out)?;
        } else if child.extension().is_some_and(|e| e == "rs")
            && std::fs::read_to_string(entry.path()).is_ok_and(|s| s.starts_with(MARKER))
        {
            out.push(child);
        }
    }
    Ok(())
}

type Key = (String, String, String); // (package, module, datatype)

/// A framework type mapped to a runtime type (T-MAP-1).
struct Builtin {
    path: TokenStream,
    /// Which Move type parameters become Rust generic parameters.
    keep: &'static [bool],
}

fn builtin(package: &str, module: &str, name: &str) -> Option<Builtin> {
    let rt = |ty: &str| -> TokenStream {
        let ty = Ident::new(ty, Span::call_site());
        quote!(__rt::#ty)
    };
    Some(match (package, module, name) {
        ("std", "string", "String") => Builtin {
            path: quote!(::std::string::String),
            keep: &[],
        },
        ("std", "ascii", "String") => Builtin {
            path: rt("AsciiString"),
            keep: &[],
        },
        ("std", "option", "Option") => Builtin {
            path: quote!(::core::option::Option),
            keep: &[true],
        },
        ("std", "type_name", "TypeName") => Builtin {
            path: rt("TypeName"),
            keep: &[],
        },
        ("sui", "object", "UID") => Builtin {
            path: rt("Uid"),
            keep: &[],
        },
        ("sui", "object", "ID") => Builtin {
            path: rt("Id"),
            keep: &[],
        },
        ("sui", "url", "Url") => Builtin {
            path: rt("Url"),
            keep: &[],
        },
        ("sui", "balance", "Balance") => Builtin {
            path: rt("Balance"),
            keep: &[false],
        },
        ("sui", "transfer", "Receiving") => Builtin {
            path: rt("Receiving"),
            keep: &[false],
        },
        ("sui", "balance", "Supply") => Builtin {
            path: rt("Supply"),
            keep: &[false],
        },
        ("sui", "coin", "Coin") => Builtin {
            path: rt("Coin"),
            keep: &[false],
        },
        ("sui", "vec_map", "VecMap") => Builtin {
            path: rt("VecMap"),
            keep: &[true, true],
        },
        ("sui", "vec_map", "Entry") => Builtin {
            path: rt("VecMapEntry"),
            keep: &[true, true],
        },
        ("sui", "vec_set", "VecSet") => Builtin {
            path: rt("VecSet"),
            keep: &[true],
        },
        ("sui", "table", "Table") | ("sui", "object_table", "ObjectTable") => Builtin {
            path: rt("Table"),
            keep: &[false, false],
        },
        ("sui", "bag", "Bag") | ("sui", "object_bag", "ObjectBag") => Builtin {
            path: rt("Table"),
            keep: &[],
        },
        ("sui", "linked_table", "LinkedTable") => Builtin {
            path: rt("LinkedTable"),
            keep: &[true, false],
        },
        ("sui", "table_vec", "TableVec") => Builtin {
            path: rt("TableVec"),
            keep: &[false],
        },
        _ => return None,
    })
}

/// System objects injected by calls (C-SYS-1), by type.
fn system_object(package: &str, module: &str, name: &str) -> Option<&'static str> {
    Some(match (package, module, name) {
        ("sui", "clock", "Clock") => "clock",
        ("sui", "random", "Random") => "random",
        ("sui", "deny_list", "DenyList") => "deny_list",
        ("sui", "accumulator", "AccumulatorRoot") => "accumulator_root",
        ("sui_system", "sui_system", "SuiSystemState") => "sui_system_state",
        ("sui", "coin_registry", "CoinRegistry") => "coin_registry",
        ("sui", "display_registry", "DisplayRegistry") => "display_registry",
        ("sui", "address_alias", "AddressAliasState") => "address_alias_state",
        _ => return None,
    })
}

fn datatype_key(d: &abi::DatatypeRef) -> Key {
    (
        d.address.trim_start_matches('@').to_owned(),
        d.module.clone(),
        d.name.clone(),
    )
}

fn is_named(t: &Type, package: &str, module: &str, name: &str) -> bool {
    matches!(t, Type::Datatype(d) if d.address == format!("@{package}") && d.module == module && d.name == name)
}

/// N-1: Rust identifiers from Move names; keywords become raw identifiers, and the few that
/// cannot be raw get a `_` suffix.
pub(crate) fn ident(name: &str) -> Ident {
    const KEYWORDS: &[&str] = &[
        "as", "break", "const", "continue", "else", "enum", "extern", "false", "fn", "for", "if",
        "impl", "in", "let", "loop", "match", "mod", "move", "mut", "pub", "ref", "return",
        "static", "struct", "trait", "true", "type", "unsafe", "use", "where", "while", "async",
        "await", "dyn", "abstract", "become", "box", "do", "final", "macro", "override", "priv",
        "typeof", "unsized", "virtual", "yield", "try", "gen",
    ];
    match name {
        "self" | "Self" | "super" | "crate" | "_" => format_ident!("{name}_"),
        n if KEYWORDS.contains(&n) => Ident::new_raw(n, Span::call_site()),
        n => Ident::new(n, Span::call_site()),
    }
}

struct Index<'l> {
    datatypes: BTreeMap<Key, &'l abi::Datatype>,
    modules: BTreeMap<(String, String), &'l abi::Module>,
}

impl<'l> Index<'l> {
    fn new(packages: &'l BTreeMap<String, PackageAbi>) -> Self {
        let mut datatypes = BTreeMap::new();
        let mut modules = BTreeMap::new();
        for (package, abi) in packages {
            for m in &abi.modules {
                modules.insert((package.clone(), m.name.clone()), m);
                for d in &m.datatypes {
                    datatypes.insert((package.clone(), m.name.clone(), d.name.clone()), d);
                }
            }
        }
        Self { datatypes, modules }
    }

    fn datatype(&self, key: &Key) -> Result<&'l abi::Datatype, Error> {
        self.datatypes.get(key).copied().ok_or_else(|| {
            Error::Closure(format!(
                "@{}::{}::{} is not in the lock",
                key.0, key.1, key.2
            ))
        })
    }
}

/// C-KIND-1: how a parameter is passed.
#[derive(Clone, Copy, Debug, PartialEq, Eq)]
enum Kind {
    TxContext,
    System(&'static str, bool),
    Receiving,
    Pure,
    Generic,
    ObjectImm,
    ObjectMut,
    ObjectByValue,
    Value,
}

/// C-PURE-1: pure layouts.
fn is_pure(t: &Type) -> bool {
    match t {
        Type::Bool
        | Type::U8
        | Type::U16
        | Type::U32
        | Type::U64
        | Type::U128
        | Type::U256
        | Type::Address => true,
        Type::Vector(inner) => is_pure(inner),
        Type::Datatype(d) => {
            (is_named(t, "std", "string", "String")
                || is_named(t, "std", "ascii", "String")
                || is_named(t, "sui", "object", "ID"))
                || (is_named(t, "std", "option", "Option")
                    && d.type_arguments.first().is_some_and(is_pure))
        }
        _ => false,
    }
}

fn has_key(index: &Index<'_>, t: &Type) -> bool {
    match t {
        Type::Datatype(d) => index
            .datatypes
            .get(&datatype_key(d))
            .is_some_and(|dt| dt.abilities.iter().any(|a| a == "key")),
        _ => false,
    }
}

fn classify(index: &Index<'_>, t: &Type) -> Kind {
    let (inner, reference) = match t {
        Type::Reference(i) => (i.as_ref(), Some(false)),
        Type::MutableReference(i) => (i.as_ref(), Some(true)),
        other => (other, None),
    };
    if let Type::Datatype(d) = inner {
        let (p, m, n) = datatype_key(d);
        if (p.as_str(), m.as_str(), n.as_str()) == ("sui", "tx_context", "TxContext") {
            return Kind::TxContext;
        }
        if let Some(name) = system_object(&p, &m, &n)
            && reference.is_some()
        {
            return Kind::System(name, reference == Some(true));
        }
        if (p.as_str(), m.as_str(), n.as_str()) == ("sui", "transfer", "Receiving")
            && reference.is_none()
        {
            return Kind::Receiving;
        }
    }
    if matches!(inner, Type::TypeParameter(_)) {
        return Kind::Generic;
    }
    if reference.is_none() && is_pure(inner) {
        return Kind::Pure;
    }
    if has_key(index, inner) {
        return match reference {
            Some(false) => Kind::ObjectImm,
            Some(true) => Kind::ObjectMut,
            None => Kind::ObjectByValue,
        };
    }
    if reference == Some(false) && is_pure(inner) {
        // `&u64` etc. are rare but legal: still a pure input.
        return Kind::Pure;
    }
    Kind::Value
}

/// Context for rendering types inside `<output>/<package>/<module>.rs`.
struct Scope<'a> {
    package: &'a str,
    module: &'a str,
    /// Per type parameter: its Rust generic name, or `None` (phantom → dropped; in functions →
    /// `Any`).
    params: &'a [Option<Ident>],
    function: bool,
}

fn keep_flags(index: &Index<'_>, key: &Key) -> Result<Vec<bool>, Error> {
    if let Some(b) = builtin(&key.0, &key.1, &key.2) {
        return Ok(b.keep.to_vec());
    }
    Ok(index
        .datatype(key)?
        .type_parameters
        .iter()
        .map(|p| !p.phantom)
        .collect())
}

fn rust_type(index: &Index<'_>, scope: &Scope<'_>, t: &Type) -> Result<TokenStream, Error> {
    Ok(match t {
        Type::Bool => quote!(bool),
        Type::U8 => quote!(u8),
        Type::U16 => quote!(u16),
        Type::U32 => quote!(u32),
        Type::U64 => quote!(u64),
        Type::U128 => quote!(u128),
        Type::U256 => quote!(__sdk::U256),
        Type::Address | Type::Signer => quote!(__sdk::Address),
        Type::Vector(inner) => {
            let inner = rust_type(index, scope, inner)?;
            quote!(::std::vec::Vec<#inner>)
        }
        Type::Reference(inner) | Type::MutableReference(inner) => rust_type(index, scope, inner)?,
        Type::TypeParameter(i) => match scope.params.get(usize::from(*i)).cloned().flatten() {
            Some(name) if !scope.function => quote!(#name),
            _ => quote!(__rt::Any),
        },
        Type::Datatype(d) => {
            let key = datatype_key(d);
            let keep = keep_flags(index, &key)?;
            let args = d
                .type_arguments
                .iter()
                .zip(keep.iter().copied().chain(std::iter::repeat(false)))
                .filter(|(_, keep)| *keep)
                .map(|(a, _)| rust_type(index, scope, a))
                .collect::<Result<Vec<_>, _>>()?;
            let path = if let Some(b) = builtin(&key.0, &key.1, &key.2) {
                b.path
            } else {
                let name = ident(&key.2);
                if key.0 == scope.package && key.1 == scope.module {
                    quote!(#name)
                } else if key.0 == scope.package {
                    let module = ident(&key.1);
                    quote!(super::#module::#name)
                } else {
                    let (package, module) = (ident(&key.0), ident(&key.1));
                    quote!(super::super::#package::#module::#name)
                }
            };
            if args.is_empty() {
                path
            } else {
                quote!(#path<#(#args),*>)
            }
        }
    })
}

/// A Move-syntax rendering of a (symbolized) type, for docs.
fn move_type(t: &Type, params: &[String]) -> String {
    match t {
        Type::Bool => "bool".into(),
        Type::U8 => "u8".into(),
        Type::U16 => "u16".into(),
        Type::U32 => "u32".into(),
        Type::U64 => "u64".into(),
        Type::U128 => "u128".into(),
        Type::U256 => "u256".into(),
        Type::Address => "address".into(),
        Type::Signer => "signer".into(),
        Type::Vector(i) => format!("vector<{}>", move_type(i, params)),
        Type::Reference(i) => format!("&{}", move_type(i, params)),
        Type::MutableReference(i) => format!("&mut {}", move_type(i, params)),
        Type::TypeParameter(i) => params
            .get(usize::from(*i))
            .cloned()
            .unwrap_or_else(|| format!("T{i}")),
        Type::Datatype(d) => {
            let args = d
                .type_arguments
                .iter()
                .map(|a| move_type(a, params))
                .collect::<Vec<_>>();
            let base = format!("{}::{}::{}", d.address, d.module, d.name);
            if args.is_empty() {
                base
            } else {
                format!("{base}<{}>", args.join(", "))
            }
        }
    }
}

fn collect_refs(t: &Type, out: &mut BTreeSet<Key>) {
    match t {
        Type::Vector(i) | Type::Reference(i) | Type::MutableReference(i) => collect_refs(i, out),
        Type::Datatype(d) => {
            out.insert(datatype_key(d));
            d.type_arguments.iter().for_each(|a| collect_refs(a, out));
        }
        _ => {}
    }
}

fn fields_of(d: &abi::Datatype) -> Vec<&abi::Field> {
    match &d.kind {
        DatatypeKind::Struct(fs) => fs.iter().collect(),
        DatatypeKind::Enum(vs) => vs.iter().flat_map(|v| &v.fields).collect(),
        DatatypeKind::NativeStruct => Vec::new(),
    }
}

fn callable(f: &abi::Function) -> bool {
    f.visibility == FunctionVisibility::Public || f.entry
}

/// Generates the module tree for `config` from `lock`'s reference network.
pub fn generate(config: &Config, lock: &Lock) -> Result<Generated, Error> {
    let network = &config.reference_network;
    let part = lock
        .networks
        .get(network)
        .ok_or_else(|| Error::Lock(format!("no {network} data; run `movegen refresh`")))?;
    let index = Index::new(&part.packages);

    // Scope: which functions get builders.
    let function_scope: Vec<(String, Option<String>)> = match &config.generate.functions {
        Some(list) => list
            .iter()
            .map(|s| match s.split_once("::") {
                Some((p, m)) => (p.to_owned(), Some(m.to_owned())),
                None => (s.clone(), None),
            })
            .collect(),
        None => config.packages.keys().map(|p| (p.clone(), None)).collect(),
    };
    for (p, m) in &function_scope {
        let known = match m {
            Some(m) => index.modules.contains_key(&(p.clone(), m.clone())),
            None => part.packages.contains_key(p),
        };
        if !known {
            return Err(Error::Config(format!(
                "[generate] functions names {p}{} which is not in the lock",
                m.as_deref().map(|m| format!("::{m}")).unwrap_or_default()
            )));
        }
    }
    let wants_functions = |package: &str, module: &str| {
        function_scope
            .iter()
            .any(|(p, m)| p == package && m.as_deref().is_none_or(|m| m == module))
    };

    // T-CLO-1: datatypes = every datatype of configured packages + everything referenced by
    // them and by selected functions, transitively.
    let mut wanted: BTreeSet<Key> = BTreeSet::new();
    let mut work: Vec<Key> = Vec::new();
    for ((package, module), m) in &index.modules {
        let configured = config.packages.contains_key(package);
        if configured {
            work.extend(
                m.datatypes
                    .iter()
                    .map(|d| (package.clone(), module.clone(), d.name.clone())),
            );
        }
        if wants_functions(package, module) {
            let mut refs = BTreeSet::new();
            for f in m.functions.iter().filter(|f| callable(f)) {
                f.parameters
                    .iter()
                    .chain(&f.returns)
                    .for_each(|t| collect_refs(t, &mut refs));
            }
            work.extend(refs);
        }
    }
    while let Some(key) = work.pop() {
        let (p, m, n) = (key.0.as_str(), key.1.as_str(), key.2.as_str());
        // `TxContext` is omitted; builtins map to runtime types (their type arguments were
        // already collected). System objects are generated (to decode them) but injected.
        if (p, m, n) == ("sui", "tx_context", "TxContext") || builtin(p, m, n).is_some() {
            continue;
        }
        if !wanted.insert(key.clone()) {
            continue;
        }
        let mut refs = BTreeSet::new();
        for f in fields_of(index.datatype(&key)?) {
            collect_refs(&f.type_, &mut refs);
        }
        work.extend(refs.into_iter().filter(|r| !wanted.contains(r)));
    }

    // Group by module and render.
    let mut modules: BTreeMap<(String, String), Vec<TokenStream>> = BTreeMap::new();
    for key in &wanted {
        let d = index.datatype(key)?;
        modules
            .entry((key.0.clone(), key.1.clone()))
            .or_default()
            .push(render_datatype(&index, key, d)?);
    }
    for ((package, module), m) in &index.modules {
        if !wants_functions(package, module) {
            continue;
        }
        let datatype_names: BTreeSet<&str> = m.datatypes.iter().map(|d| d.name.as_str()).collect();
        for f in m.functions.iter().filter(|f| callable(f)) {
            let item = render_function(&index, package, module, f, &datatype_names)?;
            modules
                .entry((package.clone(), module.clone()))
                .or_default()
                .push(item);
        }
    }

    let header = format!(
        "{MARKER} {} from the {network} lock. Do not edit; run `movegen generate`.",
        env!("CARGO_PKG_VERSION")
    );
    let mut files = Vec::new();
    let mut packages: BTreeMap<&str, Vec<&str>> = BTreeMap::new();
    for ((package, module), items) in &modules {
        packages.entry(package).or_default().push(module);
        let doc = format!(" Bindings for `@{package}::{module}`.");
        let tokens = quote! {
            #![doc = #doc]
            #![allow(non_camel_case_types, non_snake_case, unused_imports, clippy::all, clippy::pedantic)]
            use ::movegen_runtime as __rt;
            use ::movegen_runtime::IntoInput as _;
            use ::movegen_runtime::__private::serde as __serde;
            use ::movegen_runtime::__private::sui_sdk_types as __sdk;
            use ::movegen_runtime::__private::sui_transaction_builder as __tx;
            #(#items)*
        };
        files.push((
            PathBuf::from(format!("{package}/{module}.rs")),
            format_file(&header, tokens)?,
        ));
    }
    for (package, mods) in &packages {
        let mods = mods.iter().map(|m| ident(m));
        let doc = format!(" Bindings for `@{package}`.");
        files.push((
            PathBuf::from(format!("{package}/mod.rs")),
            format_file(
                &header,
                quote! { #![doc = #doc] #(#[rustfmt::skip] pub mod #mods;)* },
            )?,
        ));
    }
    let names: Vec<&str> = packages.keys().copied().collect();
    let pkg_idents = names.iter().map(|p| ident(p));
    files.push((
        PathBuf::from("mod.rs"),
        format_file(
            &header,
            quote! {
                #![doc = " Generated Sui Move bindings."]
                #(#[rustfmt::skip] pub mod #pkg_idents;)*
                /// Every package these bindings refer to; check a deployment with
                /// `Deployment::require(PACKAGES)`.
                pub const PACKAGES: &[&str] = &[#(#names),*];
            },
        )?,
    ));
    files.sort();
    Ok(Generated { files })
}

fn format_file(header: &str, tokens: TokenStream) -> Result<String, Error> {
    let file: syn::File =
        syn::parse2(tokens).map_err(|e| Error::Generate(format!("internal: {e}")))?;
    Ok(format!("{header}\n\n{}", prettyplease::unparse(&file)))
}

fn type_param_names(d: &abi::Datatype) -> Vec<Option<Ident>> {
    d.type_parameters
        .iter()
        .enumerate()
        .map(|(i, p)| {
            if p.phantom {
                None
            } else {
                Some(format_ident!("T{i}"))
            }
        })
        .collect()
}

fn render_datatype(index: &Index<'_>, key: &Key, d: &abi::Datatype) -> Result<TokenStream, Error> {
    let (package, module, name) = key;
    let rust_name = ident(name);
    let params = type_param_names(d);
    let scope = Scope {
        package,
        module,
        params: &params,
        function: false,
    };
    let generics: Vec<&Ident> = params.iter().flatten().collect();
    let gen_decl = if generics.is_empty() {
        quote!()
    } else {
        quote!(<#(#generics),*>)
    };
    let move_params: Vec<String> = d
        .type_parameters
        .iter()
        .enumerate()
        .map(|(i, p)| {
            if p.phantom {
                format!("phantom T{i}")
            } else {
                format!("T{i}")
            }
        })
        .collect();
    let doc = format!(
        " Move: `@{package}::{module}::{name}{}`{}",
        if move_params.is_empty() {
            String::new()
        } else {
            format!("<{}>", move_params.join(", "))
        },
        if d.abilities.is_empty() {
            String::new()
        } else {
            format!(" has {}", d.abilities.join(", "))
        },
    );
    let serde = quote! {
        #[derive(Clone, Debug, PartialEq, Eq, __serde::Serialize, __serde::Deserialize)]
        #[serde(crate = "__rt::__private::serde")]
    };
    let positional = |fs: &[abi::Field]| {
        !fs.is_empty()
            && fs
                .iter()
                .enumerate()
                .all(|(i, f)| f.name == format!("pos{i}"))
    };
    let type_names: Vec<String> = (0..d.type_parameters.len())
        .map(|i| format!("T{i}"))
        .collect();
    let field_doc =
        |f: &abi::Field| format!(" Move: `{}: {}`", f.name, move_type(&f.type_, &type_names));
    let body = match &d.kind {
        DatatypeKind::NativeStruct => {
            return Ok(
                quote! { #[doc = #doc] #[doc = " (native: no fields visible)"] pub enum #rust_name {} },
            );
        }
        DatatypeKind::Struct(fs) if positional(fs) => {
            let tys = fs
                .iter()
                .map(|f| rust_type(index, &scope, &f.type_))
                .collect::<Result<Vec<_>, _>>()?;
            let docs = fs.iter().map(field_doc);
            quote! { #[doc = #doc] #serde pub struct #rust_name #gen_decl(#(#[doc = #docs] pub #tys),*); }
        }
        DatatypeKind::Struct(fs) => {
            let names = fs.iter().map(|f| ident(&f.name));
            let docs = fs.iter().map(field_doc);
            let tys = fs
                .iter()
                .map(|f| rust_type(index, &scope, &f.type_))
                .collect::<Result<Vec<_>, _>>()?;
            quote! { #[doc = #doc] #serde pub struct #rust_name #gen_decl { #(#[doc = #docs] pub #names: #tys),* } }
        }
        DatatypeKind::Enum(vs) => {
            let variants = vs
                .iter()
                .enumerate()
                .map(|(tag, v)| {
                    let vname = ident(&v.name);
                    let vdoc = format!(" Move: `{name}::{}` (tag {tag})", v.name);
                    let docs = v.fields.iter().map(field_doc);
                    if v.fields.is_empty() {
                        Ok(quote!(#[doc = #vdoc] #vname))
                    } else if positional(&v.fields) {
                        let tys = v
                            .fields
                            .iter()
                            .map(|f| rust_type(index, &scope, &f.type_))
                            .collect::<Result<Vec<_>, _>>()?;
                        Ok(quote!(#[doc = #vdoc] #vname(#(#[doc = #docs] #tys),*)))
                    } else {
                        let names = v.fields.iter().map(|f| ident(&f.name));
                        let tys = v
                            .fields
                            .iter()
                            .map(|f| rust_type(index, &scope, &f.type_))
                            .collect::<Result<Vec<_>, _>>()?;
                        Ok(quote!(#[doc = #vdoc] #vname { #(#[doc = #docs] #names: #tys),* }))
                    }
                })
                .collect::<Result<Vec<_>, Error>>()?;
            quote! { #[doc = #doc] #serde pub enum #rust_name #gen_decl { #(#variants),* } }
        }
    };
    let arity = d.type_parameters.len();
    let key_impl = if d.abilities.iter().any(|a| a == "key") {
        quote!(impl #gen_decl __rt::Key for #rust_name #gen_decl {})
    } else {
        quote!()
    };
    let extension = if (package.as_str(), module.as_str(), name.as_str())
        == ("sui", "funds_accumulator", "Withdrawal")
    {
        quote! {
            impl Withdrawal {
                /// A `FundsWithdrawal` input taking `amount` of `coin_type` from the sender's
                /// address balance: the `Withdrawal<Balance<coin_type>>` that
                /// `balance::redeem_funds` / `coin::redeem_funds` consume.
                pub fn from_sender(
                    tx: &mut __tx::TransactionBuilder,
                    coin_type: __sdk::TypeTag,
                    amount: u64,
                ) -> __rt::Arg<Withdrawal> {
                    __rt::Arg::new(tx.funds_withdrawal(coin_type, amount))
                }
            }
        }
    } else {
        quote!()
    };
    Ok(quote! {
        #body
        impl #gen_decl __rt::MoveStruct for #rust_name #gen_decl {
            const PACKAGE: &'static str = #package;
            const MODULE: &'static str = #module;
            const NAME: &'static str = #name;
            const TYPE_PARAMETERS: usize = #arity;
        }
        #key_impl
        #extension
    })
}

fn render_function(
    index: &Index<'_>,
    package: &str,
    module: &str,
    f: &abi::Function,
    datatype_names: &BTreeSet<&str>,
) -> Result<TokenStream, Error> {
    let name = ident(&f.name);
    let meta = if datatype_names.contains(f.name.as_str()) {
        format_ident!("{}_call", f.name)
    } else {
        ident(&f.name)
    };
    let params: Vec<Option<Ident>> = (0..f.type_parameters.len()).map(|_| None).collect();
    let scope = Scope {
        package,
        module,
        params: &params,
        function: true,
    };
    let type_params: Vec<String> = (0..f.type_parameters.len())
        .map(|i| format!("T{i}"))
        .collect();
    let signature_doc = format!(
        " Move: `{}{}fun {module}::{}{}({}){}`",
        match f.visibility {
            FunctionVisibility::Public => "public ",
            FunctionVisibility::Friend => "public(package) ",
            FunctionVisibility::Private => "",
        },
        if f.entry { "entry " } else { "" },
        f.name,
        if type_params.is_empty() {
            String::new()
        } else {
            format!("<{}>", type_params.join(", "))
        },
        f.parameters
            .iter()
            .map(|t| move_type(t, &type_params))
            .collect::<Vec<_>>()
            .join(", "),
        match f.returns.as_slice() {
            [] => String::new(),
            [one] => format!(": {}", move_type(one, &type_params)),
            many => format!(
                ": ({})",
                many.iter()
                    .map(|t| move_type(t, &type_params))
                    .collect::<Vec<_>>()
                    .join(", ")
            ),
        }
    );
    let qualified = format!("{module}::{}", f.name);
    let fname = &f.name;
    let n_types = f.type_parameters.len();
    let (target_params, target_args) = if n_types == 0 {
        (quote!(), quote!(::std::vec::Vec::new()))
    } else {
        (
            quote!(, type_arguments: ::std::vec::Vec<__sdk::TypeTag>),
            quote!(__rt::type_arguments::<#n_types>(#qualified, type_arguments)?),
        )
    };

    let kinds: Vec<Kind> = f.parameters.iter().map(|t| classify(index, t)).collect();
    let signature: Vec<TokenStream> = kinds
        .iter()
        .filter(|k| **k != Kind::TxContext)
        .map(|k| match k {
            Kind::System(n, m) => quote!(__rt::ArgKind::System(#n, #m)),
            Kind::Receiving => quote!(__rt::ArgKind::Receiving),
            Kind::Pure => quote!(__rt::ArgKind::Pure),
            Kind::Generic => quote!(__rt::ArgKind::Generic),
            Kind::ObjectImm => quote!(__rt::ArgKind::ObjectImm),
            Kind::ObjectMut => quote!(__rt::ArgKind::ObjectMut),
            Kind::ObjectByValue => quote!(__rt::ArgKind::ObjectByValue),
            Kind::Value => quote!(__rt::ArgKind::Value),
            Kind::TxContext => unreachable!(),
        })
        .collect();
    let meta_mod = |note: &str| {
        let note = (!note.is_empty()).then(|| quote!(#[doc = ""] #[doc = #note]));
        quote! {
        #[doc = #signature_doc]
        #note
        pub mod #meta {
            use super::{__rt, __sdk};
            /// How each PTB argument is passed (system objects included, `TxContext` omitted).
            pub const SIGNATURE: &[__rt::ArgKind] = &[#(#signature),*];
            /// The call target on `d`'s network.
            pub fn target(d: &__rt::Deployment #target_params) -> ::core::result::Result<__rt::MoveTarget, __rt::CallError> {
                ::core::result::Result::Ok(__rt::MoveTarget {
                    package: d.published_at(#package)?,
                    module: #module,
                    function: #fname,
                    type_arguments: #target_args,
                })
            }
        }
        }
    };

    // C-CALL-2: reference returns and by-value TxContext are not PTB-callable.
    let by_value_tx_context = f
        .parameters
        .iter()
        .any(|t| is_named(t, "sui", "tx_context", "TxContext"));
    let returns_reference = f
        .returns
        .iter()
        .any(|t| matches!(t, Type::Reference(_) | Type::MutableReference(_)));
    if by_value_tx_context || returns_reference {
        let why = if returns_reference {
            " Returns a reference, so it is not callable from a PTB: only its `target` is generated."
        } else {
            " Takes `TxContext` by value, so it is not callable from a PTB: only its `target` is generated."
        };
        return Ok(meta_mod(why));
    }

    let mut fn_params = Vec::new();
    let mut arg_exprs = Vec::new();
    for (i, (t, kind)) in f.parameters.iter().zip(&kinds).enumerate() {
        let ty_index = i;
        match kind {
            Kind::TxContext => {}
            Kind::System(n, m) => arg_exprs.push(quote!(__rt::system_object(tx, d, #n, #m)?)),
            _ => {
                let param = format_ident!("arg{i}");
                let ty = rust_type(index, &scope, t)?;
                let k = match kind {
                    Kind::Receiving => quote!(Receiving),
                    Kind::Pure => quote!(Pure),
                    Kind::Generic => quote!(Generic),
                    Kind::ObjectImm => quote!(ObjectImm),
                    Kind::ObjectMut => quote!(ObjectMut),
                    Kind::ObjectByValue => quote!(ObjectByValue),
                    _ => quote!(Value),
                };
                // Receiving<T> params take a `ReceivingRef`, typed by the received object.
                let ty = match (kind, t) {
                    (Kind::Receiving, Type::Datatype(d)) if d.type_arguments.len() == 1 => {
                        let inner = rust_type(index, &scope, &d.type_arguments[0])?;
                        quote!(__rt::Receive<#inner>)
                    }
                    _ => ty,
                };
                fn_params.push(quote!(#param: impl __rt::IntoInput<#ty>));
                arg_exprs.push(
                    quote!(__rt::input(tx, #ty_index, __rt::ArgKind::#k, #param.into_input())?),
                );
            }
        }
    }
    let returns = f
        .returns
        .iter()
        .map(|t| rust_type(index, &scope, t))
        .collect::<Result<Vec<_>, _>>()?;
    let (ret_ty, ret_expr) = match returns.as_slice() {
        [] => (
            quote!(()),
            quote!({
                let _ = result;
                ::core::result::Result::Ok(())
            }),
        ),
        [one] => (
            quote!(__rt::Arg<#one>),
            quote!(::core::result::Result::Ok(__rt::Arg::new(result))),
        ),
        many => {
            let n = many.len();
            let items = (0..n).map(|j| quote!(__rt::Arg::new(parts[#j])));
            (
                quote!((#(__rt::Arg<#many>),*)),
                quote!({ let parts = __rt::nested(result, #n); ::core::result::Result::Ok((#(#items),*)) }),
            )
        }
    };
    let locals: Vec<Ident> = (0..arg_exprs.len())
        .map(|i| format_ident!("a{i}"))
        .collect();
    let target_call = if n_types == 0 {
        quote!(#meta::target(d)?)
    } else {
        quote!(#meta::target(d, type_arguments)?)
    };
    let type_args_param = if n_types == 0 {
        quote!()
    } else {
        quote!(type_arguments: ::std::vec::Vec<__sdk::TypeTag>,)
    };
    let meta_mod_tokens = meta_mod("");
    Ok(quote! {
        #[doc = #signature_doc]
        ///
        /// Inputs are added in parameter order; system objects are injected; `TxContext` is
        /// supplied by the chain.
        pub fn #name(
            tx: &mut __tx::TransactionBuilder,
            d: &__rt::Deployment,
            #type_args_param
            #(#fn_params),*
        ) -> ::core::result::Result<#ret_ty, __rt::CallError> {
            let target = #target_call;
            #(let #locals = #arg_exprs;)*
            let result = target.call(tx, ::std::vec![#(#locals),*]);
            #ret_expr
        }
        #meta_mod_tokens
    })
}
